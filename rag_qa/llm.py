"""LLM access for answer generation.

When ``OPENAI_API_KEY`` is set, answers are generated by the OpenAI API —
the approach taught in Module 8 of the course. Without a key, an
**extractive offline fallback** answers with the most relevant retrieved
chunk instead, so the full RAG pipeline (chunking, embeddings, retrieval,
threshold, citations) can still be run and tested end to end. The active
mode is always reported to the user; nothing is silently faked.
"""

from __future__ import annotations

import os
from typing import Protocol

DEFAULT_MODEL = "gpt-4o-mini"

SYSTEM_PROMPT = (
    "You are a careful question-answering assistant. Answer the question "
    "using ONLY the context provided. If the context does not contain the "
    "answer, reply with exactly: I don't know"
)


class AnswerGenerator(Protocol):
    """Anything that can answer a question from retrieved context."""

    name: str

    def answer(self, question: str, context_chunks: list[str]) -> str:
        """Return an answer grounded in ``context_chunks``."""
        ...


class OpenAIAnswerGenerator:
    """Generate answers with the OpenAI chat API (Module 8 pattern).

    Args:
        api_key: OpenAI API key (read from ``OPENAI_API_KEY`` if omitted).
        model: Chat model name; override with ``OPENAI_MODEL``.
    """

    name = "OpenAI"

    def __init__(
        self, api_key: str | None = None, model: str | None = None
    ) -> None:
        from openai import OpenAI

        self._client = OpenAI(api_key=api_key or os.environ["OPENAI_API_KEY"])
        self._model = model or os.environ.get("OPENAI_MODEL", DEFAULT_MODEL)

    def answer(self, question: str, context_chunks: list[str]) -> str:
        """Ask the model to answer using only the supplied context."""
        context = "\n\n".join(
            f"[Chunk {i + 1}] {chunk}" for i, chunk in enumerate(context_chunks)
        )
        response = self._client.chat.completions.create(
            model=self._model,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {
                    "role": "user",
                    "content": f"Context:\n{context}\n\nQuestion: {question}",
                },
            ],
            temperature=0.2,
        )
        return (response.choices[0].message.content or "").strip()


class ExtractiveAnswerGenerator:
    """Offline fallback: answer with the best-matching chunk's text.

    This is deliberately simple — it performs no generation — and exists so
    the retrieval pipeline can be demonstrated and tested without an API
    key. Set ``OPENAI_API_KEY`` for real generated answers.
    """

    name = "offline extractive fallback (no API key set)"

    def answer(self, question: str, context_chunks: list[str]) -> str:
        """Return the most relevant chunk verbatim as the answer."""
        if not context_chunks:
            return "I don't know"
        return context_chunks[0]


def get_answer_generator() -> AnswerGenerator:
    """Return the OpenAI generator when a key exists, else the fallback."""
    try:
        from dotenv import load_dotenv

        load_dotenv()
    except ImportError:
        pass
    if os.environ.get("OPENAI_API_KEY", "").strip():
        return OpenAIAnswerGenerator()
    return ExtractiveAnswerGenerator()
